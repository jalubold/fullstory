// Generates the FULLSTORY brand assets from the real brand font, converted to
// vector paths so they render identically everywhere:
//   - src/components/ui/wordmark.ts  (wordmark path data for the Logo component)
//   - src/app/icon.svg, public/brand-mark.svg, src/app/apple-icon.png
//   - src/app/opengraph-image.png, src/app/twitter-image.png
//
// The wordmark is "Fullstory" set in Cormorant Garamond, with the second "l"
// drawn as a ribbon bookmark that drops below the baseline — the place you keep
// in a story.
import fs from 'node:fs';
import * as fontkit from 'fontkit';
import sharp from 'sharp';

const RED = '#8e1126';
const CLOTH = '#7a1020';
const INK = '#130c0d';
const PAPER = '#fbfafa';

const font = (f) => fontkit.openSync(`src/assets/fonts/${f}.ttf`);
const r = (n) => Math.round(n * 100) / 100;
const fmt = (d) => d.replace(/-?\d+\.\d+/g, (m) => String(r(+m)));

/** Wordmark at 100px font size, baseline at y=0. Returns path data and bounds. */
function wordmark() {
  const f = font('cormorant-garamond-600');
  const size = 100;
  const scale = size / f.unitsPerEm;
  const run = f.layout('Fullstory', { kern: true, liga: false });
  let x = 0;
  let text = '';
  let ribbon = '';
  let ribbonBottom = 0;
  run.glyphs.forEach((g, i) => {
    const p = run.positions[i];
    if (i === 3) {
      const bb = g.bbox;
      const cx = x + ((bb.minX + bb.maxX) / 2) * scale;
      const w = (bb.maxX - bb.minX) * scale * 0.62;
      const top = -bb.maxY * scale;
      ribbonBottom = size * 0.33;
      const notch = w * 0.62;
      ribbon = `M${r(cx - w / 2)} ${r(top)}H${r(cx + w / 2)}V${r(ribbonBottom)}L${r(cx)} ${r(ribbonBottom - notch)}L${r(cx - w / 2)} ${r(ribbonBottom)}Z`;
    } else {
      text += g.path.scale(scale, -scale).translate(x + p.xOffset * scale, 0).toSVG();
    }
    x += p.xAdvance * scale;
  });
  const top = -f.ascent * scale * 0.86;
  return { text: fmt(text), ribbon, minX: 0, minY: r(top), width: r(x), height: r(ribbonBottom - top) };
}

const wm = wordmark();
fs.writeFileSync(
  'src/components/ui/wordmark.ts',
  `// Generated by scripts/brand-assets.mjs — do not edit by hand.\nexport const WORDMARK = ${JSON.stringify({ viewBox: `${wm.minX} ${wm.minY} ${wm.width} ${wm.height}`, text: wm.text, ribbon: wm.ribbon })} as const;\n`,
);

// Favicon: a red ribbon bookmark hanging from the top edge of a white page.

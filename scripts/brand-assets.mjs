// Generates the FULLSTORY brand assets from the real brand font, converted to
// vector paths so they render identically everywhere:
//   - src/components/ui/wordmark.ts  (wordmark path data for the Logo component)
//   - src/app/icon.svg, src/app/apple-icon.png
//   - src/app/opengraph-image.png, src/app/twitter-image.png
//
// The wordmark is simply "fullstory", all lowercase, set in Cormorant Garamond.
import fs from 'node:fs';
import * as fontkit from 'fontkit';
import sharp from 'sharp';

const RED = '#8e1126';
const CLOTH = '#7a1020';
const PAPER = '#fbfafa';

const font = (f) => fontkit.openSync(`src/assets/fonts/${f}.ttf`);
const r = (n) => Math.round(n * 100) / 100;
const fmt = (d) => d.replace(/-?\d+\.\d+/g, (m) => String(r(+m)));

/** Wordmark at 100px font size, baseline at y=0. Returns path data and bounds. */
function wordmark() {
  const f = font('cormorant-garamond-600');
  const size = 100;
  const scale = size / f.unitsPerEm;
  const run = f.layout('fullstory', { kern: true, liga: false });
  let x = 0;
  let text = '';
  run.glyphs.forEach((g, i) => {
    const p = run.positions[i];
    text += g.path.scale(scale, -scale).translate(x + p.xOffset * scale, 0).toSVG();
    x += p.xAdvance * scale;
  });
  const top = -f.ascent * scale * 0.86;
  const bottom = -f.descent * scale * 0.9;
  return { text: fmt(text), minX: 0, minY: r(top), width: r(x), height: r(bottom - top) };
}

/** A single glyph as path data, centred in a square of side `box`. */
function glyphIn(char, box, sizeRatio) {
  const f = font('cormorant-garamond-600');
  const size = box * sizeRatio;
  const scale = size / f.unitsPerEm;
  const g = f.layout(char).glyphs[0];
  const bb = g.bbox;
  const w = (bb.maxX - bb.minX) * scale;
  const h = (bb.maxY - bb.minY) * scale;
  const tx = (box - w) / 2 - bb.minX * scale;
  const ty = (box + h) / 2 + bb.minY * scale;
  return fmt(g.path.scale(scale, -scale).translate(tx, ty).toSVG());
}

const wm = wordmark();
fs.writeFileSync(
  'src/components/ui/wordmark.ts',
  `// Generated by scripts/brand-assets.mjs — do not edit by hand.\nexport const WORDMARK = ${JSON.stringify({ viewBox: `${wm.minX} ${wm.minY} ${wm.width} ${wm.height}`, text: wm.text })} as const;\n`,
);

// Favicon: a deep red serif lowercase "f" on a white page.
const iconBody = (s = 64) => `<rect width="${s}" height="${s}" rx="${s * 0.22}" fill="${PAPER}"/><path d="${glyphIn('f', s, 0.9)}" fill="${RED}"/>`;
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">${iconBody()}</svg>`;
fs.writeFileSync('src/app/icon.svg', iconSvg);
await sharp(Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="180" height="180" viewBox="0 0 180 180"><rect width="180" height="180" fill="${PAPER}"/><path d="${glyphIn('f', 180, 0.86)}" fill="${RED}"/></svg>`))
  .png()
  .toFile('src/app/apple-icon.png');

// Linen texture used on the cloth background.
const linen = `<pattern id="linen" width="6" height="6" patternUnits="userSpaceOnUse"><rect width="6" height="6" fill="${CLOTH}"/><path d="M0 1.5H6M0 4.5H6" stroke="#000" stroke-opacity=".07" stroke-width="1"/><path d="M1.5 0V6M4.5 0V6" stroke="#fff" stroke-opacity=".035" stroke-width="1"/></pattern>
<radialGradient id="light" cx=".35" cy=".3" r=".9"><stop offset="0" stop-color="#fff" stop-opacity=".07"/><stop offset=".6" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".35"/></radialGradient>`;

// Open Graph image: the wordmark blind-stamped on a deep red cloth cover.
const sans = font('inter-500');
function textPath(f, text, size, x, y, tracking = 0) {
  const scale = size / f.unitsPerEm;
  const run = f.layout(text);
  const width = run.positions.reduce((w, p) => w + p.xAdvance * scale + tracking * size, 0) - tracking * size;
  let cx = x - width / 2;
  let d = '';
  run.glyphs.forEach((g, i) => {
    d += g.path.scale(scale, -scale).translate(cx, y).toSVG();
    cx += run.positions[i].xAdvance * scale + tracking * size;
  });
  return fmt(d);
}
const s = 2.6;
const ox = 600 - (wm.width * s) / 2;
const oy = 300;
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630"><defs>${linen}</defs>
  <rect width="1200" height="630" fill="url(#linen)"/><rect width="1200" height="630" fill="url(#light)"/>
  <rect x="36" y="36" width="1128" height="558" fill="none" stroke="#fff" stroke-opacity=".14"/>
  <g transform="translate(${r(ox)} ${oy}) scale(${s})"><path d="${wm.text}" fill="${PAPER}"/></g>
  <path d="${textPath(sans, 'YOUR PHOTOS. YOUR STORY. YOUR BOOK.', 17, 600, 470, 0.32)}" fill="#fff" fill-opacity=".72"/>
</svg>`;
await sharp(Buffer.from(og)).png().toFile('src/app/opengraph-image.png');
fs.copyFileSync('src/app/opengraph-image.png', 'src/app/twitter-image.png');

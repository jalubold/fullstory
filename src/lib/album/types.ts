import type { FontId } from './fonts';
import type { OrnamentId } from './ornaments';

/**
 * Album document model.
 *
 * All element geometry is normalised to the TRIM size of a page: x/y/w/h are
 * fractions (0..1) of page width/height. Physical properties (font size,
 * border width, corner radius, stroke width) are in PostScript points (1/72 in)
 * at the project's actual trim size. The same model is rendered by the browser
 * (editor, previews, thumbnails) and by the PDF renderer, so they stay in sync.
 */

export type Orientation = 'square' | 'landscape' | 'portrait';

export interface PageSize {
  /** Product size id from the catalog configuration, e.g. "square-8". */
  id: string;
  label: string;
  widthMm: number;
  heightMm: number;
}

export interface Crop {
  /** 1 = image just covers the frame. >1 zooms in. */
  zoom: number;
  /** Focal point (0..1) of the visible window within the overflow area. */
  fx: number;
  fy: number;
}

export type TextRole = 'title' | 'subtitle' | 'heading' | 'body' | 'caption' | 'label';

interface BaseElement {
  id: string;
  x: number;
  y: number;
  w: number;
  h: number;
  /** Degrees, clockwise, around the element centre. */
  rotation: number;
  locked?: boolean;
  /** True when the element was generated by a layout slot (replaced on layout change). */
  fromLayout?: boolean;
}

export type PhotoFilter = 'none' | 'bw' | 'sepia';

export interface PhotoElement extends BaseElement {
  type: 'photo';
  photoId: string | null;
  crop: Crop;
  shape: 'rect' | 'ellipse';
  /** Corner radius in pt (rect only). */
  radius: number;
  /** Mat/border drawn inside the frame, in pt. */
  borderWidth: number;
  borderColor: string;
  filter: PhotoFilter;
}

export type TextAlign = 'left' | 'center' | 'right';
export type TextVAlign = 'top' | 'middle' | 'bottom';

export interface TextStyle {
  font: FontId;
  weight: number;
  italic: boolean;
  /** Font size in pt. */
  size: number;
  color: string;
  /** Unitless multiplier. */
  lineHeight: number;
  /** Tracking in em. */
  letterSpacing: number;
  uppercase: boolean;
}

export interface TextElement extends BaseElement, TextStyle {
  type: 'text';
  text: string;
  align: TextAlign;
  valign: TextVAlign;
  role?: TextRole;
}

export interface ShapeElement extends BaseElement {
  type: 'shape';
  shape: 'rect' | 'ellipse' | 'line';
  fill: string | null;
  stroke: string | null;
  /** pt */
  strokeWidth: number;
  /** pt (rect only) */
  radius: number;
  opacity: number;
}

export interface OrnamentElement extends BaseElement {
  type: 'ornament';
  ornament: OrnamentId;
  color: string;
  opacity: number;
}

export type AlbumElement = PhotoElement | TextElement | ShapeElement | OrnamentElement;
export type ElementType = AlbumElement['type'];

export type BackgroundPattern = 'none' | 'dots' | 'grid' | 'lines' | 'frame' | 'double-frame' | 'corners';

export interface Background {
  color: string;
  pattern: BackgroundPattern;
  patternColor: string;
}

export interface Page {
  id: string;
  /** Layout last applied to this page (informational; elements are the source of truth). */
  layoutId: string | null;
  background: Background;
  elements: AlbumElement[];
}

export interface Theme {
  text: Record<TextRole, TextStyle>;
  colors: { text: string; muted: string; accent: string; inverse: string };
  background: Background;
  photo: { borderWidth: number; borderColor: string; radius: number };
  /** Curated colours offered in pickers for this design. */
  palette: string[];
}

/** How pages change in the online album (preview and share link). */
export type PageAnimation = 'flip' | 'fade' | 'slide' | 'zoom' | 'reveal';

/** Settings for viewing the album on screen. They never affect the PDF. */
export interface Presentation {
  animation: PageAnimation;
  /** Photos drift slowly while the album is open, like a film. */
  livingPhotos: boolean;
  /** Background music: a direct link to an audio file, played when the album opens. */
  musicUrl: string | null;
}

export interface AlbumDocument {
  schemaVersion: 1;
  templateId: string | null;
  orientation: Orientation;
  size: PageSize;
  theme: Theme;
  cover: Page;
  backCover: Page;
  pages: Page[];
  spineText: string;
  presentation?: Presentation;
}

/** A page reference within a document. */
export type PageRef = { kind: 'cover' } | { kind: 'back' } | { kind: 'page'; index: number };

/** Minimal information needed to render a photo. */
export interface PhotoAsset {
  id: string;
  width: number;
  height: number;
  /** Returns a URL for the given target pixel width. */
  thumbUrl: string;
  displayUrl: string;
  /** Optional URL builder for sources that can resize on the fly (samples). */
  urlTemplate?: string;
  placeholder?: string;
  alt?: string;
}

export type PhotoMap = Record<string, PhotoAsset>;
